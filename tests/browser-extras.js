async (page) => {
  const base = new URL(page.url()).origin;
  const check = (v,m) => {if(!v) throw new Error(m);};
  const errors=[]; page.on('pageerror',e=>errors.push(String(e)));
  await page.locator('#choose-teacher').click();
  await page.locator('#teacher-password').fill('extras-test-only');
  await page.locator('#login-form button').click();
  await page.locator('#activity-title').fill('額外功能驗收');
  await page.locator('#question-numbers').fill('1\n2');
  await page.locator('#create-form button').click();
  await page.locator('#settings-form').waitFor({state:'visible'});
  await page.locator('#quiz-mode').selectOption('sequential');
  await page.locator('#quiz-fairness').check();
  await page.locator('#settings-form button').click();
  await page.locator('#notice').filter({hasText:'活動規則已儲存'}).waitFor();
  const student=await page.context().newPage(); await student.goto(base);
  await student.locator('#join-code').fill(await page.locator('#session-code').innerText());
  await student.locator('#join-group').fill('驗收A組');
  await student.locator('#join-form button').click();
  await page.locator('#start').click();
  await student.waitForFunction(()=>!document.querySelector('#answer-0').disabled);
  check(await student.locator('#answer-1').isDisabled(),'future question enabled');
  await student.locator('#answer-0').fill('測試答案');
  await student.locator('.question-card').nth(0).locator('button').click();
  await page.locator('#close-round').click();
  await page.locator('#next-round').waitFor({state:'visible'});
  await page.locator('#next-round').click();
  await student.waitForFunction(()=>!document.querySelector('#answer-1').disabled);
  await page.locator('#close-round').click();
  await student.locator('#results').waitFor({state:'visible'});
  const download=page.waitForEvent('download'); await page.locator('#download-csv').click();
  check((await download).suggestedFilename().endsWith('.csv'),'CSV download missing');
  check(await student.locator('#download-csv').isHidden(),'teacher CSV visible to student');
  await page.screenshot({path:'output/playwright/extras-teacher.png',fullPage:true});
  await student.setViewportSize({width:390,height:844});
  check(await student.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'mobile overflow');
  await student.screenshot({path:'output/playwright/extras-student.png',fullPage:true});
  check(!errors.length,errors.join('\n')); await student.close();
  return {passed:true,features:['E-01','E-02'],pageErrors:errors};
}
