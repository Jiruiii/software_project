async (page) => {
  const base = new URL(page.url()).origin;
  const check = (v,m) => {if(!v) throw new Error(m);};
  const errors=[]; page.on('pageerror',e=>errors.push(String(e)));
  await page.locator('#choose-teacher').click();
  await page.locator('#teacher-password').fill('extras-test-only');
  await page.locator('#login-form button').click();
  await page.locator('#activity-title').fill('額外功能驗收');
  await page.locator('#question-numbers').fill('1\n2');
  await page.locator('#create-form button').click();
  await page.locator('#settings-form').waitFor({state:'visible'});
  await page.locator('#quiz-mode').selectOption('sequential');
  await page.locator('#quiz-fairness').check();
  await page.locator('#settings-form button').click();
  await page.locator('#notice').filter({hasText:'活動規則已儲存'}).waitFor();
  const student=await page.context().newPage(); await student.goto(base);
  await student.locator('#join-code').fill(await page.locator('#session-code').innerText());
  await student.locator('#join-group').fill('驗收A組');
  await student.locator('#join-form button').click();
  await page.locator('#start').click();
  await student.waitForFunction(()=>!document.querySelector('#answer-0').disabled);
  check(await student.locator('#answer-1').isDisabled(),'future question enabled');
  await student.locator('#answer-0').fill('測試答案');
  await student.locator('#stake-0').selectOption('3');
  await student.reload(); await student.waitForFunction(()=>!document.querySelector('#answer-0')?.disabled);
  check(await student.locator('#answer-0').inputValue()==='測試答案','draft not restored');
  check(await student.locator('#stake-0').inputValue()==='3','draft stake not restored');
  await student.route('**/api/activities/*/answers', async route=>{await route.fetch(); await route.abort();});
  await student.locator('.question-card').nth(0).locator('button').click();
  await student.waitForFunction(()=>document.querySelector('.question-card').classList.contains('sent'));
  await student.unroute('**/api/activities/*/answers');
  check(await student.locator('#stake-0').inputValue()==='3','stake not preserved');
  await page.locator('#close-round').click();
  await page.locator('#next-round').waitFor({state:'visible'});
  await page.locator('#next-round').click();
  await student.waitForFunction(()=>!document.querySelector('#answer-1').disabled);
  await student.locator('#answer-1').fill('尚未送出的草稿');
  await student.route('**/api/**', route=>route.abort());
  await student.waitForFunction(()=>document.querySelector('#connection').classList.contains('offline'));
  await student.unroute('**/api/**');
  await student.waitForFunction(()=>!document.querySelector('#connection').classList.contains('offline'));
  check(await student.locator('#answer-1').inputValue()==='尚未送出的草稿','reconnect lost draft');
  await page.locator('#close-round').click();
  await student.locator('#results').waitFor({state:'visible'});
  const download=page.waitForEvent('download'); await page.locator('#download-csv').click();
  check((await download).suggestedFilename().endsWith('.csv'),'CSV download missing');
  check(await student.locator('#download-csv').isHidden(),'teacher CSV visible to student');
  check(await student.locator('#replay').isHidden(),'student replay exposed');
  const before = await page.evaluate(()=>JSON.stringify(current.answers));
  await page.locator('#replay-play').click(); await page.locator('#replay-play').click();
  const paused = await page.locator('#replay-answers').innerText();
  await page.waitForTimeout(1700);
  check(await page.locator('#replay-answers').innerText()===paused,'pause failed');
  await page.locator('#replay-play').click();
  await page.waitForFunction(()=>document.querySelector('#replay-status').textContent.includes('播放完成'));
  check((await page.locator('#replay-answers').innerText()).includes('驗收A組：測試答案'),'replay answer missing');
  await page.locator('#replay-question').selectOption('2'); await page.locator('#replay-reset').click();
  await page.waitForFunction(()=>document.querySelector('#replay-status').textContent.includes('無成功組別'));
  check(before===await page.evaluate(()=>JSON.stringify(current.answers)),'replay changed records');
  await page.getByRole('button',{name:'驗收A組 第 1 題判為錯誤',exact:true}).click();
  await student.waitForFunction(()=>!document.querySelector('#results').textContent.includes('搶答成功'));
  await page.getByRole('button',{name:'驗收A組 第 1 題判為正確',exact:true}).click();
  await student.waitForFunction(()=>document.querySelector('#results').textContent.includes('搶答成功（正確）'));
  await page.locator('#cluster-refresh').click();
  await page.waitForFunction(()=>document.querySelector('#cluster-list').textContent.includes('驗收A組：測試答案'));
  check(await student.locator('#classification').isHidden(),'student clusters exposed');
  await page.locator('#reference-0').fill('老師提供的參考答案');
  await page.locator('#reference-forms form').first().locator('button').click();
  await student.waitForFunction(()=>document.querySelector('#report-table').textContent.includes('老師提供的參考答案'));
  check((await student.locator('#report-table').innerText()).includes('正確'),'report verdict missing');
  const reportDownload=student.waitForEvent('download'); await student.locator('#download-report').click();
  check((await reportDownload).suggestedFilename().endsWith('.csv'),'report download missing');
  check(await student.locator('#references').isHidden(),'student reference editing exposed');
  await page.screenshot({path:'output/playwright/extras-teacher.png',fullPage:true});
  await student.setViewportSize({width:390,height:844});
  check(await student.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'mobile overflow');
  await student.screenshot({path:'output/playwright/extras-student.png',fullPage:true});
  await student.locator('#logout').click(); await student.locator('#join-form').waitFor({state:'visible'});
  check(await student.evaluate(()=>!Object.keys(sessionStorage).some(k=>k.startsWith('classroom.draft.'))),'logout retained draft');
  check(!errors.length,errors.join('\n')); await student.close();
  return {passed:true,features:['E-01','E-02','E-03','E-04','E-05','E-06','E-07','E-08'],pageErrors:errors};
}
